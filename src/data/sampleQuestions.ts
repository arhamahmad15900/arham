// Generates an extended 100 questions set or N questions for any mock test
export function generateQuestionSet(count: number = 25): Question[] {
  if (count <= NIELIT_SAMPLE_QUESTIONS.length) {
    return NIELIT_SAMPLE_QUESTIONS.slice(0, count);
  }
  
  // Extend dynamically if host selects 50 or 100 questions
  const questions: Question[] = [...NIELIT_SAMPLE_QUESTIONS];
  let currentId = NIELIT_SAMPLE_QUESTIONS.length + 1;
  
  const additionalTopics = [
    { q: "CSS का पूर्ण रूप क्या होता है?", opts: ["A. Cascading Style Sheets", "B. Creative System Style", "C. Computer Styling Sheet", "D. Colorful Style Syntax"], ans: 0 },
    { q: "Which memory is non-volatile in nature?", opts: ["A. SRAM", "B. DRAM", "C. ROM (Read-Only Memory)", "D. Virtual Memory"], ans: 2 },
    { q: "Python में लिस्ट (List) किस प्रकार के ब्रैकेट से बनती है?", opts: ["A. ()", "B. {}", "C. []", "D. <>"], ans: 2 },
    { q: "What is the port number for HTTP by default?", opts: ["A. 21", "B. 25", "C. 80", "D. 443"], ans: 2 },
    { q: "Word processor में वर्तनी (Spelling Check) की कुंजी क्या है?", opts: ["A. F2", "B. F7", "C. F5", "D. F11"], ans: 1 },
    { q: "What is phishing attack prevention best practice?", opts: ["A. Click all email links", "B. Verify sender email and enable 2FA", "C. Disable firewall", "D. Use simple passwords"], ans: 1 },
    { q: "Artificial Intelligence (AI) में मुख्य भाषा कौन सी अधिक उपयोग होती है?", opts: ["A. Python", "B. Pascal", "C. BASIC", "D. HTML"], ans: 0 },
    { q: "Cloud Computing में SaaS का क्या अर्थ है?", opts: ["A. System as a Service", "B. Software as a Service", "C. Storage as a Service", "D. Security as a Service"], ans: 1 },
    { q: "QR Code का पूर्ण रूप क्या है?", opts: ["A. Quick Response Code", "B. Quality Record Code", "C. Query Request Code", "D. Quantum Read Code"], ans: 0 },
    { q: "MAC Address कितने bits का होता है?", opts: ["A. 32 bits", "B. 48 bits", "C. 64 bits", "D. 128 bits"], ans: 1 }
  ];

  while (questions.length < count) {
    const template = additionalTopics[(questions.length - 25) % additionalTopics.length];
    questions.push({
      id: currentId,
      text: `[Q${currentId}] ${template.q}`,
      options: template.opts,
      marks: 1,
      correctOption: template.ans
    });
    currentId++;
  }
  
  return questions;
}
